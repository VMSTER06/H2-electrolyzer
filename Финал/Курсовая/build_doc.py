    add_p("Целью данного курсового проекта является разработка микропроцессорного устройства технического зрения для учебного мобильного робота. Проект носит учебно-демонстрационный характер с целью наглядного представления принципов оптико-электронного восприятия, базовой пространственной локализации и фильтрации контрастных цветовых меток. Проектируемое устройство не предназначено для интеграции в промышленное производство, автоматические конвейерные линии или эксплуатацию в жестких производственных условиях.")
