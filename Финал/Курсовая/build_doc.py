        "2 РАЗРАБОТКА СТРУКТУРЫ УСТРОЙСТВА ТЕХНИЧЕСКОГО ЗРЕНИЯ РОБОТА",
        "  2.1 Постановка задачи",
        "  2.2 Определение компонентов структуры устройства",
        "  2.3 Взаимодействие компонентов устройства",
