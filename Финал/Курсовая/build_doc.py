import docx
from docx.shared import Mm, Pt, RGBColor, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import parse_xml
from docx.oxml.ns import nsdecls

def create_document():
    doc = docx.Document()

    # 1. Настройка параметров страницы (ГОСТ)
    for section in doc.sections:
        section.top_margin = Mm(20)
        section.bottom_margin = Mm(20)
        section.left_margin = Mm(30)
        section.right_margin = Mm(15)

    # 2. Базовый стиль шрифта
    normal_style = doc.styles['Normal']
    normal_style.font.name = 'Times New Roman'
    normal_style.font.size = Pt(14)
    normal_style.font.color.rgb = RGBColor(0, 0, 0)

    # Вспомогательные функции оформления
    def add_p(text, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_after=0):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.first_line_indent = Mm(12.5)
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(space_after)
        run = p.add_run(text)
        run.bold = bold
        run.italic = italic
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        return p

    def add_bullet(text):
        p = doc.add_paragraph(style='List Bullet')
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.first_line_indent = Mm(0)
        p.paragraph_format.left_indent = Mm(18)
        p.paragraph_format.space_after = Pt(2)
        run = p.runs[0] if p.runs else p.add_run()
        run.text = text
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)

    def add_h1(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(16)
        p.paragraph_format.space_after = Pt(8)
        p.paragraph_format.first_line_indent = Mm(12.5)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.bold = True
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)

    def add_h2(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.first_line_indent = Mm(12.5)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.bold = True
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)

    def add_table_custom(title, headers, data, col_widths=None):
        if title:
            tp = doc.add_paragraph()
            tp.alignment = WD_ALIGN_PARAGRAPH.LEFT
            tp.paragraph_format.line_spacing = 1.5
            tp.paragraph_format.first_line_indent = Mm(12.5)
            tp.paragraph_format.space_before = Pt(8)
            tp.paragraph_format.space_after = Pt(4)
            tr = tp.add_run(title)
            tr.font.name = 'Times New Roman'
            tr.font.size = Pt(14)

        table = doc.add_table(rows=len(data) + 1, cols=len(headers))
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        
        # XML-стилизация сетки границ таблицы
        tblPr = table._tbl.tblPr
        tblBorders = parse_xml(
            r'<w:tblBorders %s>'
            r'<w:top w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'<w:bottom w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'<w:left w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'<w:right w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'<w:insideH w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'<w:insideV w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'</w:tblBorders>' % nsdecls('w')
        )
        tblPr.append(tblBorders)

        # Заполнение шапки
        hdr_row = table.rows[0]
        for idx, h_text in enumerate(headers):
            cell = hdr_row.cells[idx]
            cell.text = h_text
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.line_spacing = 1.15
            p.paragraph_format.space_before = Pt(3)
            p.paragraph_format.space_after = Pt(3)
            for r in p.runs:
                r.bold = True
                r.font.name = 'Times New Roman'
                r.font.size = Pt(11)

        # Заполнение данных
        for r_idx, row_values in enumerate(data):
            row = table.rows[r_idx + 1]
            for c_idx, val in enumerate(row_values):
                cell = row.cells[c_idx]
                cell.text = str(val)
                p = cell.paragraphs[0]
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER if c_idx != 1 and len(str(val)) < 25 else WD_ALIGN_PARAGRAPH.LEFT
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.space_before = Pt(2)
                p.paragraph_format.space_after = Pt(2)
                for r in p.runs:
                    r.font.name = 'Times New Roman'
                    r.font.size = Pt(10.5)

        if col_widths:
            for row in table.rows:
                for idx, w in enumerate(col_widths):
                    row.cells[idx].width = Mm(w)

        doc.add_paragraph().paragraph_format.space_after = Pt(6)

    def add_code(code_str):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.first_line_indent = Mm(0)
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(4)
        run = p.add_run(code_str)
        run.font.name = 'Consolas'
        run.font.size = Pt(9.5)

    # ================== 1. ЛИСТ ЗАДАНИЯ ==================
    add_h1("ЗАДАНИЕ НА КУРСОВОЙ ПРОЕКТ (ЛИСТ ЗАДАНИЯ)")
    add_p("Тема проекта: Разработка микропроцессорного устройства технического зрения робота", bold=True)
    add_p("1. Исходные данные к проекту:", bold=True)
