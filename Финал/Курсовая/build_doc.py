        "ВВЕДЕНИЕ",
        "1 ОБЗОР ЛИТЕРАТУРЫ ПО ТЕМЕ «УСТРОЙСТВА ТЕХНИЧЕСКОГО ЗРЕНИЯ РОБОТОВ»",
        "  1.1 Состав и назначение устройства",
        "  1.2 Вычислительный контроллер",
        "  1.3 Видеосенсор (КМОП-матрица)",
