"""Э1 (А3) по образцу структурной схемы Лазовского: обобщенные блоки вокруг микроконтроллера, связи — линии
без стрелок с изломами под 90°, пульт — второй микроконтроллер, связанный через модули приема и передачи данных.
Питание на схеме не показывается (замечание 26.10.2026)."""
import io, json

d = json.load(io.open('e1_a3.json', encoding='utf-8'))
items = []
N = '\\n'
W, H = 52, 28
SZ = 13


def box(x, y, text, w=W, h=H):
    items.append({"t": "box", "x": x, "y": y, "w": w, "h": h, "text": text, "size": SZ})


def line(*pts):
    items.append({"t": "line", "pts": [list(p) for p in pts]})


def label(x, y, s):
    items.append({"t": "text", "x": x, "y": y, "w": 16, "h": 5, "text": s, "size": 11, "a": "l"})


R = [28, 74, 120, 166, 207]           # верх строк
cy = [r + H / 2 for r in R]

# ---------------- блок управления ----------------
C1, C2, C3 = 35, 124, 213            # левые края колонок
box(C2, R[2], "Микроконтроллер" + N + "устройства" + N + "контроля")
mL, mR, mT, mB = C2, C2 + W, R[2], R[2] + H

box(C1, R[0], "Модуль" + N + "управления")
line((C1 + W, cy[0]), (140, cy[0]), (140, mT))
box(C3, R[0], "Исполнительные" + N + "устройства")
line((C3, cy[0]), (160, cy[0]), (160, mT))
box(C1, R[1], "Датчик" + N + "давления")
line((C1 + W, cy[1]), (132, cy[1]), (132, mT))
box(C3, R[1], "Модуль" + N + "отображения" + N + "информации")
line((C3, cy[1]), (168, cy[1]), (168, mT))
box(C1, R[2], "Датчик" + N + "температуры")
line((C1 + W, cy[2]), (mL, cy[2]))
box(C3, R[2], "Блок" + N + "индикации")
line((mR, cy[2]), (C3, cy[2]))
box(C1, R[3], "Датчик" + N + "наклона")
line((C1 + W, cy[3]), (132, cy[3]), (132, mB))
box(C3, R[3], "Блок звуковой" + N + "сигнализации")
line((C3, cy[3]), (168, cy[3]), (168, mB))
box(C2, R[4], "Модуль" + N + "приема и передачи" + N + "данных")
line((150, R[4]), (150, mB))

# ---------------- пульт ----------------
P1, P2 = 290, 360
box(P1, R[2], "Микроконтроллер" + N + "устройства" + N + "удаленного" + N + "управления")
pL, pR, pT, pB = P1, P1 + W, R[2], R[2] + H
pc = P1 + W / 2
box(P1, R[0], "Модуль" + N + "управления")
line((pc, R[0] + H), (pc, pT))
box(P2, R[1], "Модуль" + N + "отображения" + N + "информации")
line((P2, cy[1]), (330, cy[1]), (330, pT))
box(P2, R[2], "Блок" + N + "индикации")
line((pR, cy[2]), (P2, cy[2]))
box(P2, R[3], "Блок звуковой" + N + "сигнализации")
line((P2, cy[3]), (330, cy[3]), (330, pB))
box(P1, R[4], "Модуль" + N + "приема и передачи" + N + "данных")
line((pc, R[4]), (pc, pB))

# радиоканал между модулями приема и передачи данных
line((C2 + W, cy[4]), (P1, cy[4]))

d['items'] = items
json.dump(d, io.open('e1_a3.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(len(items), 'items')
