def table_page(s, cols, heads, rows, y_top, y_bot, rh=8.0, hh=15.0, first=True):
    x0 = s.fx
    W = sum(cols)
    s.line([(x0, y_top), (x0 + W, y_top)], LW_MAIN)
    s.line([(x0, y_top + hh), (x0 + W, y_top + hh)], LW_MAIN)
    x = x0
    for w, h in zip(cols, heads):
        s.text_fit(x + w / 2, y_top + hh / 2, w - 1.5, h, 3.5 if chr(10) not in h else 2.8)
        x += w
        s.line([(x, y_top), (x, y_bot)], LW_MAIN)
    n = int((y_bot - y_top - hh) // rh)
    for i in range(1, n + 1):
        s.line([(x0, y_top + hh + i * rh), (x0 + W, y_top + hh + i * rh)], LW_THIN)
    used = 0
    for i, r in enumerate(rows[:n]):
        yy = y_top + hh + i * rh + rh / 2 + 0.6
        used += 1
        if r is None: continue
        if r[0] == '#':
            xc = x0 + cols[0] + cols[1] / 2
            s.text(xc, yy, r[1], 3.5)
            tw = s.d.textlength(r[1], font=font(3.5)) / (300 / 25.4)
            s.line([(xc - tw / 2, yy + 2.6), (xc + tw / 2, yy + 2.6)], 0.25)
            continue
        x = x0
        for j, (w, v) in enumerate(zip(cols, r)):
            if v:
                if j == 1: s.text_fit(x + 1.5, yy, w - 3, v, 3.5, 'lm')
                elif j == 0: s.text_fit(x + w / 2, yy, w - 1.0, v, 2.6)
                else: s.text_fit(x + w / 2, yy, w - 2, v, 3.5)
            x += w
    return used


def perechen(out):
    cols, heads = [20, 110, 10, 45], ['Поз.\nобозна-\nчение', 'Наименование', 'Кол.', 'Примечание']
    pages = []
    rows = list(PE)
    sheet_no = 1
    total = 2
    while rows:
        s = Sheet(210, 297); s.frame(DES + ' ПЭ3', box=False)
        if sheet_no == 1:
            yb = s.stamp_form2(dict(BASE, designation=DES + ' ПЭ3', name=NAME + 'Перечень элементов',
                                    sheet='1', sheets=str(total)))
        else:
            yb = s.stamp_form2a(dict(designation=DES + ' ПЭ3', sheet=str(sheet_no)))
        s.rect(s.fx, s.fy, 185, yb - s.fy, LW_MAIN)
        used = table_page(s, cols, heads, rows, s.fy, yb)
        rows = rows[used:]
        pages.append(s); sheet_no += 1
    pages[0].img.save(out + '.pdf', 'PDF', resolution=300, save_all=True, append_images=[p.img for p in pages[1:]])
    for i, p in enumerate(pages): p.save(f'{out}_{i + 1}.png')
    return len(pages)


