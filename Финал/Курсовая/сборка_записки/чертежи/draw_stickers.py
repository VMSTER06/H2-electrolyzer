"""Наклейки внутрь корпусов (требование преподавателя 27.10.2026): таблица подключения разъемов
и назначение кнопок и светодиодов. Лист А4, наклейки в натуральную величину, линия реза — тонкая рамка.
Usage: py -3 draw_stickers.py <out>   (создает <out>.png и <out>.pdf)"""
import sys
from eskd import Sheet, LW_LINE, LW_THIN

W = 180.0   # ширина наклейки, мм


def sticker(s, x, y, title, groups):
    """groups: [(заголовок группы, [(обозначение, описание), ...]), ...]; возвращает нижнюю границу"""
    rh, c1 = 6.0, 34.0
    yy = y + 9
    s.text(x + W / 2, y + 5, title, 4.0)
    for head, rows in groups:
        s.rect(x, yy, W, rh, LW_LINE)
        s.text(x + W / 2, yy + rh / 2, head, 3.2)
        yy += rh
        for a, b in rows:
            s.rect(x, yy, c1, rh, LW_THIN); s.rect(x + c1, yy, W - c1, rh, LW_THIN)
            s.text(x + c1 / 2, yy + rh / 2, a, 3.0)
            s.text_fit(x + c1 + 2, yy + rh / 2, W - c1 - 4, b, 3.0, 'lm')
            yy += rh
        yy += 2
    s.rect(x - 3, y - 2, W + 6, yy - y + 3, LW_THIN, dash=(3, 2))   # линия реза
    return yy + 6


