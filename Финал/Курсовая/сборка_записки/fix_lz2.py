"""Укладка в 35 страниц после доводки по Лазовскому: компактная таблица 4.1, без итогового абзаца раздела 1,
объединение пунктов 5.2."""
import io, sys
sys.stdout.reconfigure(encoding='utf-8')
fn = sys.argv[1]
L = io.open(fn, encoding='utf-8-sig').read().split('\n')
norm = lambda s: s.replace(' ', ' ')
# раздел 1: итоговый абзац (у Лазовского подраздел заканчивается ссылкой на источники)
L = [l for l in L if not norm(l).startswith('#P Таким образом, по результатам обзора литературы')]
# таблица 4.1
a = next(i for i, l in enumerate(L) if norm(l).startswith('#T Таблица 4.1 – Назначение выводов плат'))
b = next(i for i in range(a, len(L)) if L[i] == '#TEND')
L[a:b + 1] = [
    '#T Таблица 4.1 – Назначение выводов плат микроконтроллеров {w:13,15,36,36}',
    '#R Логический номер контакта|Вывод платы|Устройство контроля|Устройство удаленного управления',
    '#R 101|3V3|Питание 3,3 В|Питание 3,3 В',
    '#R 103|GPIO 36|Датчик давления BP1|–',
    '#R 105|GPIO 34|–|Кнопка SB6',
    '#R 107|GPIO 32|Ключ A5 электролизера|Кнопка SB10',
    '#R 108|GPIO 33|Кнопка SB3|Кнопка SB11',
    '#R 109|GPIO 25|Реле K1, вход IN3|Кнопка SB7',
    '#R 110|GPIO 26|Реле K1, вход IN1|Кнопка SB8',
    '#R 111|GPIO 27|Реле K1, вход IN2|Кнопка SB9',
    '#R 112|GPIO 14|Кнопка SB2|Светодиод HL4',
    '#R 113|GPIO 12|Светодиод HL2|Светодиод HL6',
    '#R 114, 201|GND|Общий провод|Общий провод',
    '#R 115|GPIO 13|Кнопка SB1|Светодиод HL5',
    '#R 119|5V|Питание 5 В|Питание 5 В',
    '#R 202, 208–210, 213|GPIO 23, 19, 18, 5, 4|Радиомодуль A1 (SPI)|Радиомодуль A2 (SPI)',
    '#R 203, 206|GPIO 22, 21|Шина I2C: A3, A4|Шина I2C: HG2',
    '#R 211|GPIO 17|Светодиод HL1|Кнопка SB5',
    '#R 212|GPIO 16|Ключ VT1 излучателя|Кнопка SB4',
    '#R 215|GPIO 2|Светодиод HL3|Ключ VT2 излучателя',
    '#R 216|GPIO 15|Датчик температуры BK1|–',
    '#TEND',
]
# 5.2: объединение пунктов
i = next(i for i, l in enumerate(L) if norm(l).startswith('#P Блоки 9–11 –'))
j = next(i for i, l in enumerate(L) if norm(l).startswith('#P Блоки 12, 13 –'))
assert j == i + 1
L[i] = '#P Блоки 9–13 – измерение давления и угла наклона с проверкой порогов защиты каждые 100 мс, температуры – один раз в секунду.'
del L[j]
io.open(fn, 'w', encoding='utf-8-sig').write('\n'.join(L))
print('ok')
