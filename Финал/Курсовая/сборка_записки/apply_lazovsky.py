import io, re, sys
sys.stdout.reconfigure(encoding='utf-8')
fn = sys.argv[1]
L = io.open(fn, encoding='utf-8-sig').read().split('\n')
norm = lambda s: s.replace(' ', ' ')


def idx(pred, start=0):
    r = [i for i in range(start, len(L)) if pred(norm(L[i]))]
    assert r, 'not found'
    return r[0]


def last_par_before(head_prefix):
    i = idx(lambda l: l.startswith(head_prefix))
    j = i - 1
    while L[j] == '#E': j -= 1
    return j


