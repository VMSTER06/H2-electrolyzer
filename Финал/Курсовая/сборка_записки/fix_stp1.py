"""СТП 2.3.12: диапазоны в тексте — «от … до …»; числа до девяти без единиц — словами."""
import io, sys
sys.stdout.reconfigure(encoding='utf-8')
R = [('в течение 3–5 с с частотой не более 2–3 Гц', 'в течение от 3 до 5 с с частотой не более 3 Гц'),
     ('должен мигать в течение 3–5 с', 'должен мигать в течение от 3 до 5 с'),
     ('с расстояния 2–3 м', 'с расстояния от 2 до 3 м'),
     ('аналоговый датчик давления на 0–10 бар', 'аналоговый датчик давления с диапазоном от 0 до 10 бар'),
     ('Ток базы в 7 раз превышает', 'Ток базы в семь раз превышает')]
for fn in sys.argv[1:]:
    s = io.open(fn, encoding='utf-8-sig').read()
    n = 0
    for a, b in R:
        a2 = a.replace(' ', ' ')
        for v in {a, a.replace('3–5 с', '3–5 с').replace('2–3 Гц', '2–3 Гц').replace('2–3 м', '2–3 м').replace('0–10 бар', '0–10 бар')}:
            if v in s:
                n += s.count(v); s = s.replace(v, b)
    io.open(fn, 'w', encoding='utf-8-sig').write(s)
    print(fn, n)
