"""Переименование: блок управления (мозг) -> устройство контроля; пульт -> устройство удаленного управления.
Usage: py -3 rename_units.py files... ; изменяются только строки разметки (не листинги прошивок)."""
import io, re, sys
sys.stdout.reconfigure(encoding='utf-8')
NB = '[  ]'
R = [
    (r'([Пп])ульт' + NB + r'дистанционного' + NB + r'управления', lambda m: ('У' if m.group(1) == 'П' else 'у') + 'стройство удаленного управления'),
    (r'([Бб])лок' + NB + r'управления', 'стройство контроля', ''),
    (r'([Бб])лока' + NB + r'управления', 'стройства контроля', ''),
    (r'([Бб])локу' + NB + r'управления', 'стройству контроля', ''),
    (r'([Бб])локом' + NB + r'управления', 'стройством контроля', ''),
    (r'([Бб])локе' + NB + r'управления', 'стройстве контроля', ''),
    (r'([Пп])ульт(?![а-яё])', 'стройство удаленного управления', ''),
    (r'([Пп])ульта(?![а-яё])', 'стройства удаленного управления', ''),
    (r'([Пп])ульту(?![а-яё])', 'стройству удаленного управления', ''),
    (r'([Пп])ультом(?![а-яё])', 'стройством удаленного управления', ''),
    (r'([Пп])ульте(?![а-яё])', 'стройстве удаленного управления', ''),
]
def cap(ch): return 'У' if ch in 'БП' else 'у'
for fn in sys.argv[1:]:
    s = io.open(fn, encoding='utf-8-sig').read()
    total = 0
    out = []
    for l in s.split('\n'):
        if l.startswith('#LISTING'):
            out.append(l); continue
        for item in R:
            if callable(item[1]):
                l, k = re.subn(item[0], item[1], l)
            else:
                tail = item[1]
                l, k = re.subn(item[0], lambda m, t=tail: cap(m.group(1)) + t, l)
            total += k
        out.append(l)
    io.open(fn, 'w', encoding='utf-8-sig').write('\n'.join(out))
    print(fn, total)
