"""Пульт: аккумулятор 18650 2000 мА·ч -> Li-Pol 3,7 В 1500 мА·ч (пересчет времени автономной работы, источник [25])."""
import io, sys
sys.stdout.reconfigure(encoding='utf-8')
NB = ' '
R = [
    ('литий-ионный аккумулятор 18650 пульта с контроллером заряда TP4056',
     'литий-полимерный аккумулятор 3,7 В, 1500 мА·ч пульта с контроллером заряда TP4056'),
    ('литий-ионный аккумулятор с модулем заряда и повышающим преобразователем в пульте',
     'литий-полимерный аккумулятор с модулем заряда и повышающим преобразователем в пульте'),
    ('Пульт питается от литий-ионного аккумулятора типоразмера 18650 емкостью 2000 мА·ч',
     'Пульт питается от литий-полимерного аккумулятора напряжением 3,7 В и емкостью 1500 мА·ч'),
    ('а продолжительность автономной работы – 2000 / 13 ≈ 154 ч',
     'а продолжительность автономной работы – 1500 / 13 ≈ 115 ч'),
    ('продолжительность работы составляет около 80 ч',
     'продолжительность работы составляет около 60 ч'),
    ('пульт работает от аккумулятора 18650 не менее 80 ч',
     'пульт работает от литий-полимерного аккумулятора 1500 мА·ч около 115 ч в типовом режиме'),
    ('#PL [25] NCR18650B : Lithium Ion Battery [Электронный ресурс] / Panasonic Corporation. – Режим доступа : https://industrial.panasonic.com/cdbs/www-data/pdf2/ACA4000/ACA4000CE240.pdf. – Дата доступа : 10.10.2026.',
     '#PL [25] Li-ion Polymer Battery 1500 mAh 3.7 V (333283) : Datasheet [Электронный ресурс] / Soldered Electronics. – Режим доступа : https://www.mouser.com/catalog/specsheets/Soldered_333283%20li-ion%20battery%201500mah%2037v.pdf. – Дата доступа : 11.10.2026.'),
]
for fn in sys.argv[1:]:
    s = io.open(fn, encoding='utf-8-sig').read()
    had_nb = NB in s
    s = s.replace(NB, ' ')
    n = 0
    for a, b in R:
        if a in s:
            s = s.replace(a, b); n += 1
    io.open(fn, 'w', encoding='utf-8-sig').write(s)
    print(fn, 'replaced', n, 'left 18650:', s.count('18650'), 'nbsp removed' if had_nb else '')
